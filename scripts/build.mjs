// Builds dist/tokens.css and dist/tokens.json from src/tokens.json.
// No dependencies: run with `node scripts/build.mjs`.
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from "node:fs";

const src = JSON.parse(readFileSync(new URL("../src/tokens.json", import.meta.url)));

// Type sizes come from a modular scale, rounded to whole pixels, output in rem.
const typeSizes = Object.fromEntries(
  Object.entries(src.type.steps).map(([name, step]) => {
    const px = Math.round(src.type.base * Math.pow(src.type.ratio, step));
    return [name, px];
  })
);

const rem = (px) => `${+(px / 16).toFixed(4)}rem`;

function colorVars(mode) {
  return Object.entries(src.color[mode]).map(([k, v]) => `  --color-${k}: ${v};`);
}

const shared = [
  ...Object.entries(src.font.family).map(([k, v]) => `  --font-${k}: ${v};`),
  ...Object.entries(src.font.weight).map(([k, v]) => `  --weight-${k}: ${v};`),
  ...Object.entries(typeSizes).map(([k, px]) => `  --text-${k}: ${rem(px)};`),
  ...Object.entries(src.type.leading).map(([k, v]) => `  --leading-${k}: ${v};`),
  ...Object.entries(src.space).map(([k, px]) => `  --space-${k}: ${rem(px)};`),
  ...Object.entries(src.radius).map(([k, px]) => `  --radius-${k}: ${k === "pill" ? "999px" : rem(px)};`),
];

const css = `/* Generated by scripts/build.mjs from src/tokens.json. Do not edit by hand. */
:root {
${[...shared, ...colorVars("light")].join("\n")}
  color-scheme: light;
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${colorVars("dark").map((l) => "  " + l).join("\n")}
    color-scheme: dark;
  }
}

:root[data-theme="dark"] {
${colorVars("dark").join("\n")}
  color-scheme: dark;
}
`;

// Contrast report, so every text color is checked against the backgrounds it sits on.
function luminance(hex) {
  const c = hex.replace("#", "").match(/../g).map((h) => parseInt(h, 16) / 255);
  const [r, g, b] = c.map((v) => (v <= 0.03928 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4)));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}
export function contrast(a, b) {
  const [l1, l2] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (l1 + 0.05) / (l2 + 0.05);
}

const report = [];
let failed = 0;
for (const mode of ["light", "dark"]) {
  const c = src.color[mode];
  const pairs = [
    ["ink", "paper"], ["ink", "surface"], ["ink-muted", "paper"], ["ink-muted", "surface"],
    ["accent", "surface"], ["on-accent", "accent"],
    ["approve", "surface"], ["caution", "surface"], ["reject", "surface"],
  ];
  for (const [fg, bg] of pairs) {
    const ratio = contrast(c[fg], c[bg]);
    const pass = ratio >= 4.5;
    if (!pass) failed++;
    report.push({ mode, fg, bg, ratio: +ratio.toFixed(2), pass });
  }
}

mkdirSync(new URL("../dist/", import.meta.url), { recursive: true });
writeFileSync(new URL("../dist/tokens.css", import.meta.url), css);
writeFileSync(
  new URL("../dist/tokens.json", import.meta.url),
  JSON.stringify({ ...src, type: { ...src.type, sizes: typeSizes }, contrast: report }, null, 2) + "\n"
);

// The preview site reads the same built files.
copyFileSync(new URL("../dist/tokens.css", import.meta.url), new URL("../docs/tokens.css", import.meta.url));
copyFileSync(new URL("../dist/tokens.json", import.meta.url), new URL("../docs/tokens.json", import.meta.url));

for (const r of report) {
  console.log(`${r.pass ? "ok  " : "FAIL"} ${r.mode.padEnd(5)} ${r.fg} on ${r.bg}: ${r.ratio}`);
}
if (failed) {
  console.error(`\n${failed} pairing(s) below 4.5:1`);
  process.exit(1);
}
console.log("\nWrote dist/ and copied to docs/");
